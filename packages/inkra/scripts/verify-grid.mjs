import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../../../apps/docs/package.json', import.meta.url));
const { build } = require('esbuild');
const { chromium } = require('playwright');
const bundle = await build({ entryPoints: [new URL('../test/fixtures/grid-runtime.tsx', import.meta.url).pathname], bundle: true, write: false, format: 'esm', jsx: 'automatic', platform: 'browser' });
const css = await readFile(new URL('../dist/styles.css', import.meta.url), 'utf8');
const tokens = await readFile(new URL('../dist/tokens.css', import.meta.url), 'utf8');
const server = createServer((req, res) => {
  res.setHeader('Content-Type', req.url === '/app.js' ? 'text/javascript' : 'text/html');
  res.end(req.url === '/app.js' ? bundle.outputFiles[0].text : `<!doctype html><style>${tokens}\n${css}\nbody{margin:16px}#layout,#tracks{display:block;font-size:12px}input{max-width:90%}</style><div id="root"></div><script type="module" src="/app.js"></script>`);
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  const state = async () => JSON.parse(await page.locator('#layout').textContent());
  const move = page.getByRole('button', { name: 'Drag item: Card a' });
  const resize = page.getByRole('button', { name: 'Resize panels: Card a' });
  await move.focus();
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => JSON.parse(document.querySelector('#layout').textContent)[0].x === 1);
  await resize.focus();
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => JSON.parse(document.querySelector('#layout').textContent)[0].w === 5);
  const accepted = await state();
  await page.locator('#reject').click();
  await move.focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForTimeout(200);
  assert.deepEqual(await state(), accepted);
  const x = await page.locator('[data-grid-item="a"]').evaluate(element => element.getBoundingClientRect().x);
  assert.ok(x > 70, `Rejected movement must restore original x, got ${x}`);
  await page.locator('#reject').click();
  const input = page.getByRole('textbox', { name: 'Input a' });
  await input.fill('Persist across widths');
  const inputBox = await input.boundingBox();
  await page.mouse.move(inputBox.x + 5, inputBox.y + 5);
  await page.mouse.down();
  await page.mouse.move(inputBox.x + 120, inputBox.y + 5, { steps: 6 });
  await page.mouse.up();
  assert.deepEqual(await state(), accepted, 'Body controls cannot move a card');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.waitForSelector('#board[data-stacked="true"]');
  assert.equal(await input.inputValue(), 'Persist across widths');
  assert.equal(await page.locator('#board .inkra-grid-board__move').count(), 0);
  await page.screenshot({ path: '/tmp/inkra-grid-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1100, height: 900 });
  await page.waitForSelector('#board:not([data-stacked])');
  assert.deepEqual(await state(), accepted);
  assert.equal(await input.inputValue(), 'Persist across widths');
  const handle = page.locator('#tracks-grid [role="separator"][aria-orientation="vertical"]').first();
  await handle.focus();
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => JSON.parse(document.querySelector('#tracks').textContent).columns.a > 50);
  const widths = await page.locator('[data-cell$="-a"]').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().width));
  assert.ok(Math.abs(widths[0] - widths[1]) < 1, 'Columns stay aligned between rows');
  const rowHandle = page.locator('#tracks-grid [role="separator"][aria-orientation="horizontal"]').first();
  await rowHandle.focus();
  await page.keyboard.press('ArrowDown');
  await page.waitForFunction(() => JSON.parse(document.querySelector('#tracks').textContent).rows.top > 50);
  const trackState = await page.locator('#tracks').textContent();
  await page.locator('#reject').click();
  await handle.focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#tracks').textContent(), trackState, 'Rejected track resize preserves owner values');
  await page.locator('#reject').click();
  const before = await state();
  const box = await move.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 180, box.y + box.height / 2, { steps: 12 });
  await page.mouse.up();
  await page.waitForTimeout(200);
  assert.notDeepEqual(await state(), before, 'Pointer dragging changes grid position');
  const beforeResize = await state();
  const resizeBox = await resize.boundingBox();
  await page.mouse.move(resizeBox.x + resizeBox.width / 2, resizeBox.y + resizeBox.height / 2);
  await page.mouse.down();
  await page.mouse.move(resizeBox.x + resizeBox.width / 2 + 90, resizeBox.y + resizeBox.height / 2 + 52, { steps: 10 });
  await page.mouse.up();
  await page.waitForTimeout(150);
  assert.ok((await state())[0].w > beforeResize[0].w, 'Pointer resize changes card width');
  assert.ok((await state())[0].h > beforeResize[0].h, 'Pointer resize changes card height');
  const changeCount = await page.locator('#changes').textContent();
  const finalItem = (await state())[0];
  await page.locator('#constraints').click();
  await page.waitForFunction(({ w, h }) => {
    const input = document.querySelector('[aria-label="Input a"]');
    return input.dataset.minW === String(w) && input.dataset.maxW === String(w)
      && input.dataset.minH === String(h) && input.dataset.maxH === String(h);
  }, finalItem);
  await resize.focus();
  for (const key of ['ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown']) await page.keyboard.press(key);
  await page.waitForTimeout(150);
  assert.equal((await state())[0].w, finalItem.w, 'Rerendered width constraints apply to keyboard');
  assert.equal((await state())[0].h, finalItem.h, 'Rerendered height constraints apply to keyboard');
  await page.locator('#static').click();
  await page.waitForFunction(() => !document.querySelector('[data-grid-item="a"] .inkra-grid-board__move'));
  assert.equal(await page.locator('[data-grid-item="a"] .inkra-grid-board__resize').isDisabled(), true);
  await page.locator('#static').click();
  await page.waitForFunction(() => Boolean(document.querySelector('[data-grid-item="a"] .inkra-grid-board__move')));
  await page.locator('#move-flag').click();
  await page.waitForFunction(() => !document.querySelector('[data-grid-item="a"] .inkra-grid-board__move'));
  await page.locator('#resize-flag').click();
  await page.waitForFunction(() => document.querySelector('[data-grid-item="a"] .inkra-grid-board__resize').disabled);
  await page.locator('#move-flag').click();
  await page.locator('#resize-flag').click();
  await page.waitForFunction(() => !document.querySelector('[data-grid-item="a"] .inkra-grid-board__resize').disabled);
  await page.locator('#disabled').click();
  assert.equal(await page.locator('#board .inkra-grid-board__move').count(), 0);
  assert.ok(await page.locator('#board .inkra-grid-board__resize').evaluateAll(elements => elements.every(element => element.disabled && element.tabIndex === -1)));
  await page.locator('#disabled').click();
  await page.locator('#custom-labels').click();
  assert.equal(await page.getByRole('button', { name: 'move a', exact: true }).count(), 1);
  assert.equal(await page.getByRole('button', { name: 'resize a', exact: true }).count(), 1);
  assert.equal(await page.locator('#changes').textContent(), changeCount, 'Prop-only changes and constrained no-ops emit no layout change');
  await page.locator('#unlock-constraints').click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Input a"]').dataset.minW === '2'
    && !document.querySelector('[aria-label="Input a"]').hasAttribute('data-max-w'));
  await page.getByRole('button', { name: 'resize a', exact: true }).focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(w => JSON.parse(document.querySelector('#layout').textContent)[0].w === w - 1, finalItem.w);
  await page.screenshot({ path: '/tmp/inkra-grid-desktop.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: grid keyboard/pointer move and resize, controlled rejection, mobile state, synchronized tracks, dynamic constraints/flags, disabled semantics and labels');
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
}
